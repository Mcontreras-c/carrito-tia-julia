WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET DEFINE OFF

CREATE TABLE categorias (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    nombre NVARCHAR2(80) NOT NULL,
    activa NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_categorias PRIMARY KEY (id),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
    CONSTRAINT ck_categorias_activa CHECK (activa IN (0, 1))
);

CREATE TABLE productos (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    categoria_id NUMBER(19) NOT NULL,
    nombre NVARCHAR2(120) NOT NULL,
    precio NUMBER(12,0) NOT NULL,
    imagen NVARCHAR2(500),
    disponible NUMBER(1) DEFAULT 1 NOT NULL,
    activo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_productos PRIMARY KEY (id),
    CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id) REFERENCES categorias (id),
    CONSTRAINT uq_productos_cat_nombre UNIQUE (categoria_id, nombre),
    CONSTRAINT ck_productos_precio CHECK (precio > 0),
    CONSTRAINT ck_productos_disponible CHECK (disponible IN (0, 1)),
    CONSTRAINT ck_productos_activo CHECK (activo IN (0, 1))
);

CREATE TABLE pedidos (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    cliente NVARCHAR2(120),
    estado NVARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    observaciones NVARCHAR2(500),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_pedidos PRIMARY KEY (id),
    CONSTRAINT ck_pedidos_estado CHECK (
        estado IN ('PENDIENTE', 'EN_PREPARACION', 'ENTREGADO', 'CANCELADO')
    )
);

CREATE INDEX ix_pedidos_estado_fecha ON pedidos (estado, creado_en);

CREATE TABLE detalles_pedido (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pedido_id NUMBER(19) NOT NULL,
    producto_id NUMBER(19) NOT NULL,
    nombre_producto NVARCHAR2(120) NOT NULL,
    cantidad NUMBER(6,0) NOT NULL,
    precio_unitario NUMBER(12,0) NOT NULL,
    indicaciones NVARCHAR2(500),
    CONSTRAINT pk_detalles_pedido PRIMARY KEY (id),
    CONSTRAINT fk_detalles_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT fk_detalles_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_detalles_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalles_precio CHECK (precio_unitario > 0)
);

CREATE INDEX ix_detalles_pedido ON detalles_pedido (pedido_id);
CREATE INDEX ix_detalles_producto ON detalles_pedido (producto_id);

CREATE TABLE pagos (
    id NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    pedido_id NUMBER(19) NOT NULL,
    metodo NVARCHAR2(20) NOT NULL,
    monto NUMBER(18,0) NOT NULL,
    recibido NUMBER(18,0),
    vuelto NUMBER(18,0),
    referencia NVARCHAR2(120),
    creado_en TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_pagos PRIMARY KEY (id),
    CONSTRAINT uq_pagos_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_pagos_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos (id),
    CONSTRAINT ck_pagos_metodo CHECK (metodo IN ('EFECTIVO', 'TRANSFERENCIA', 'TARJETA')),
    CONSTRAINT ck_pagos_monto CHECK (monto > 0),
    CONSTRAINT ck_pagos_efectivo CHECK (
        (metodo = 'EFECTIVO' AND recibido IS NOT NULL AND vuelto IS NOT NULL
            AND recibido >= monto AND vuelto = recibido - monto)
        OR
        (metodo IN ('TRANSFERENCIA', 'TARJETA') AND recibido IS NULL AND vuelto IS NULL)
    )
);

COMMENT ON COLUMN productos.precio IS 'Pesos chilenos enteros; validar entradas sin decimales antes de guardar.';
COMMENT ON COLUMN productos.imagen IS 'Ruta o clave de la imagen; el archivo se almacena fuera de Oracle.';
COMMENT ON COLUMN pedidos.id IS 'Numero visible de pedido, global; puede tener saltos.';
COMMENT ON COLUMN pedidos.actualizado_en IS 'La API actualiza esta fecha al modificar el pedido o sus detalles.';
COMMENT ON COLUMN detalles_pedido.nombre_producto IS 'Copia del nombre al vender; conserva el historial.';
COMMENT ON COLUMN detalles_pedido.precio_unitario IS 'Copia del precio al vender; no cambia al editar el menu.';
COMMENT ON TABLE pagos IS 'Un pago completo por pedido. Sin pagos parciales ni devoluciones en esta version.';

-- Totales derivados: no se duplica el total del pedido en una columna editable.
CREATE OR REPLACE VIEW resumen_pedidos AS
SELECT p.id, p.cliente, p.estado, p.creado_en,
       NVL(d.total, 0) AS total,
       CASE WHEN pa.id IS NULL THEN 'SIN_PAGAR' ELSE 'PAGADO' END AS estado_pago,
       pa.metodo AS metodo_pago, pa.monto AS monto_pagado
FROM pedidos p
LEFT JOIN (
    SELECT pedido_id, SUM(cantidad * precio_unitario) AS total
    FROM detalles_pedido GROUP BY pedido_id
) d ON d.pedido_id = p.id
LEFT JOIN pagos pa ON pa.pedido_id = p.id;

